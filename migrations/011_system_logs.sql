CREATE TABLE IF NOT EXISTS system_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  level TEXT NOT NULL CHECK (level IN ('info', 'warn', 'error')),
  category TEXT NOT NULL CHECK (category IN ('auth', 'api', 'action', 'error', 'frontend', 'system')),
  method TEXT,
  route TEXT,
  status_code INTEGER,
  duration_ms INTEGER,
  actor_uid UUID,
  actor_role TEXT,
  school_id UUID,
  ip_hash TEXT,
  user_agent TEXT CHECK (char_length(user_agent) <= 255),
  message TEXT CHECK (char_length(message) <= 1000),
  metadata JSONB
);

CREATE INDEX IF NOT EXISTS idx_system_logs_created_at
  ON system_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_system_logs_category
  ON system_logs (category);
CREATE INDEX IF NOT EXISTS idx_system_logs_level
  ON system_logs (level);
CREATE INDEX IF NOT EXISTS idx_system_logs_actor_uid
  ON system_logs (actor_uid);
CREATE INDEX IF NOT EXISTS idx_system_logs_school_id
  ON system_logs (school_id);

